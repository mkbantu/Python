
#slicing the the string

my_string = "This is My String !"
print(len(my_string))
print(my_string[0])
print(my_string[len(my_string)-1])

print(my_string[len(my_string) - 1])
print(my_string[-1])
print(my_string[1:7])
print(my_string[0:7:2])
print("=========")
print(my_string[13:2:-1])
print(my_string[17:0:-2])
print(my_string[:])
print(my_string[:: -1])